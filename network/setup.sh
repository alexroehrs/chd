#!/usr/bin/env bash
# Generates a fresh 4-validator Hyperledger Besu QBFT network (keys + genesis).
# Usage: BLOCK_PERIOD=2 VALIDATORS=4 bash network/setup.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BLOCK_PERIOD="${BLOCK_PERIOD:-2}"
VALIDATORS="${VALIDATORS:-4}"
CHAIN_ID="${CHAIN_ID:-2026}"
BESU="${BESU:-besu}"

rm -rf "$HERE/generated" "$HERE/data"
mkdir -p "$HERE/generated"

cat > "$HERE/generated/qbftConfigFile.json" <<EOF
{
  "genesis": {
    "config": {
      "chainId": ${CHAIN_ID},
      "berlinBlock": 0,
      "londonBlock": 0,
      "zeroBaseFee": true,
      "qbft": {
        "blockperiodseconds": ${BLOCK_PERIOD},
        "epochlength": 30000,
        "requesttimeoutseconds": $(( BLOCK_PERIOD * 2 > 4 ? BLOCK_PERIOD * 2 : 4 ))
      }
    },
    "nonce": "0x0",
    "timestamp": "0x58ee40ba",
    "gasLimit": "0x1fffffffffffff",
    "difficulty": "0x1",
    "mixHash": "0x63746963616c2062797a616e74696e65206661756c7420746f6c6572616e6365",
    "coinbase": "0x0000000000000000000000000000000000000000",
    "alloc": {}
  },
  "blockchain": {
    "nodes": { "generate": true, "count": ${VALIDATORS} }
  }
}
EOF

$BESU operator generate-blockchain-config \
  --config-file="$HERE/generated/qbftConfigFile.json" \
  --to="$HERE/generated/networkFiles" \
  --private-key-file-name=key >/dev/null

i=1
for d in "$HERE"/generated/networkFiles/keys/*/; do
  mkdir -p "$HERE/data/node$i"
  cp "$d/key" "$d/key.pub" "$HERE/data/node$i/"
  i=$((i + 1))
done
cp "$HERE/generated/networkFiles/genesis.json" "$HERE/generated/genesis.json"

# Docker Compose alternative (same keys and genesis): docker compose -f network/generated/docker-compose.yml up -d
BESU_IMAGE="${BESU_IMAGE:-hyperledger/besu:26.9.0}"
pub1=$(sed 's/^0x//' "$HERE/data/node1/key.pub")
{
  echo "# generated by network/setup.sh"
  echo "services:"
  for i in $(seq 1 "$VALIDATORS"); do
    boot=""
    [ "$i" -gt 1 ] && boot="      - --bootnodes=enode://${pub1}@172.28.0.11:30303"
    cat <<EOF
  node$i:
    image: ${BESU_IMAGE}
    environment:
      - JAVA_OPTS=-Xmx1g
    volumes:
      - ../data/node$i:/data
      - ./genesis.json:/config/genesis.json:ro
    command:
      - --data-path=/data
      - --genesis-file=/config/genesis.json
      - --node-private-key-file=/data/key
      - --p2p-host=172.28.0.1$i
      - --rpc-http-enabled
      - --rpc-http-host=0.0.0.0
      - --rpc-http-api=ETH,NET,QBFT,WEB3,TXPOOL
      - --rpc-http-max-active-connections=2000
      - --host-allowlist=*
      - --rpc-http-cors-origins=*
      - --min-gas-price=0
      - --tx-pool-max-future-by-sender=2000
$boot
    ports:
      - "$((8544 + i)):8545"
    networks:
      chd:
        ipv4_address: 172.28.0.1$i
EOF
  done
  cat <<EOF
networks:
  chd:
    ipam:
      config:
        - subnet: 172.28.0.0/16
EOF
} | sed '/^$/d' > "$HERE/generated/docker-compose.yml"

echo "QBFT network generated: ${VALIDATORS} validators, block period ${BLOCK_PERIOD}s, chainId ${CHAIN_ID}"
